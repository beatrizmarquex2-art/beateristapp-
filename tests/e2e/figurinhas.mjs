// Álbum de figurinhas (iPhone 390x844): abre, recebe pacotes de presente, abre o pacote, cola, filtra, amplia e confere que não entrega nada em dobro.
import { serve, launch, sleep, check, done, fakeLogin } from './harness.mjs';
const { srv, url } = await serve();
const { browser, ctx } = await launch();
const page = await ctx.newPage(); await page.setViewportSize({ width: 390, height: 844 });
const errs = []; page.on('pageerror', (e) => errs.push(String(e).slice(0, 200)));
await fakeLogin(ctx, page, url);
const go = (h) => page.evaluate((x) => { location.hash = x; }, h);
await go('#/figurinhas'); await page.waitForSelector('.fig-tabs', { timeout: 8000 });
check('abre o álbum', (await page.textContent('.fig-total')).includes('0/125'));
await page.getByRole('tab', { name: /comum/ }).click(); await sleep(500);
check('livro Comum: capa + sumário + 20 páginas (80 figurinhas, 4 por página)', (await page.locator('.lv-page').count()) === 22);
await page.screenshot({ path: '/tmp/claude-0/fig-album.png' });
await page.getByRole('tab', { name: /pacotes/ }).click();
check('2 pacotes de presente (boas-vindas + do dia)', (await page.textContent('.fig-pack-card p')).startsWith('2 pacotes'));
await page.getByRole('button', { name: 'abrir pacote' }).click(); await sleep(500);
await page.screenshot({ path: '/tmp/claude-0/fig-pack.png' });
check('5 cartas no pacote', (await page.locator('.fig-flip').count()) === 5);
for (const b of await page.locator('.fig-flip').all()) await b.click();
await sleep(700); await page.screenshot({ path: '/tmp/claude-0/fig-pack2.png' });
await page.getByRole('button', { name: 'colar tudo no álbum' }).click(); await sleep(400);
const after = await page.textContent('.fig-total');
check('colou (pelo menos 1 de 125)', /^[1-5]\/125/.test(after.trim()), after);
await page.reload(); await page.waitForSelector('.fig-tabs'); await sleep(600);
const again = await page.textContent('.fig-total');
check('progresso persiste ao recarregar', /^[1-5]\/125/.test(again.trim()), again);
await page.getByRole('tab', { name: /pacotes/ }).click();
check('reabrir o app não devolve o pacote já aberto', (await page.textContent('.fig-pack-card p')).startsWith('1 pacote'));
await page.getByRole('tab', { name: /comum/ }).click(); await sleep(800);
await page.locator('.lv-idx').click(); await sleep(500);
const gotPage = await page.evaluate(() => { const hit = [...document.querySelectorAll('.lv-slot.got')]; return hit.length; });
for (let i = 0; i < 22 && !(await page.locator('.lv-slot.got').count()); i++) { await page.locator('.lv-nav[aria-label="Próxima página"]').click(); await sleep(450); }
await page.locator('.lv-slot.got').first().click(); await sleep(500);
check('detalhe abre', await page.locator('.fig-zoom > svg').count() === 1);
await page.screenshot({ path: '/tmp/claude-0/fig-detail.png' });
const png = async (fmt, rotulo) => { await page.getByRole('radio', { name: rotulo }).click(); await sleep(350); const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 30000 }), page.getByRole('button', { name: 'baixar / compartilhar' }).click()]); const f = await dl.path(); const { readFileSync } = await import('node:fs'); const b = readFileSync(f); return { nome: dl.suggestedFilename(), w: b.readUInt32BE(16), h: b.readUInt32BE(20), kb: Math.round(b.length / 1024), ok: b.subarray(0, 8).toString('hex') === '89504e470d0a1a0a' }; };
const post = await png('post', 'post (feed)'), story = await png('story', 'story'), carta = await png('carta', 'só a cartinha');
check('baixar post do feed: PNG 1080x1350', post.ok && post.w === 1080 && post.h === 1350 && post.kb > 200, JSON.stringify(post));
check('baixar story: PNG 1080x1920', story.ok && story.w === 1080 && story.h === 1920 && story.kb > 200, JSON.stringify(story));
check('baixar só a cartinha: PNG 1080x1425', carta.ok && carta.w === 1080 && carta.h === 1425, JSON.stringify(carta));
await page.getByRole('radio', { name: 'post (feed)' }).click(); await page.getByRole('radio', { name: 'Palco' }).click(); await sleep(350);
const palco = await (async () => { const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 30000 }), page.getByRole('button', { name: 'baixar / compartilhar' }).click()]); return dl.suggestedFilename(); })();
check('modelo Palco no nome do arquivo', /_post_palco\.png$/.test(palco), palco);
check('nome do arquivo com código e artista', /^F\d{3}_[A-Z0-9_]+_post\.png$/.test(post.nome), post.nome);
await page.keyboard.press('Escape'); await sleep(400);
await page.getByRole('tab', { name: /beatlemania/ }).click(); await sleep(300);
check('livro Beatlemania: capa + sumário + 6 páginas (22 figurinhas)', (await page.locator('.lv-page').count()) === 8);
await page.getByRole('tab', { name: /minhas/ }).click(); await sleep(400);
check('aba Minhas no álbum (vazia, com atalho pro Perfil)', (await page.textContent('.mc')).includes('nenhuma ainda') && (await page.locator('a[href="#/perfil"]').count()) >= 1);
check('sem erros de página', errs.length === 0, errs.join(' | '));
await browser.close(); srv.close(); done();
