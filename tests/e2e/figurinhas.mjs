// Álbum de figurinhas (iPhone 390x844): abre, recebe pacotes de presente, abre o pacote, cola, filtra, amplia e confere que não entrega nada em dobro.
import { serve, launch, sleep, check, done, fakeLogin } from './harness.mjs';
const { srv, url } = await serve();
const { browser, ctx } = await launch();
const page = await ctx.newPage(); await page.setViewportSize({ width: 390, height: 844 });
const errs = []; page.on('pageerror', (e) => errs.push(String(e).slice(0, 200)));
await fakeLogin(ctx, page, url);
const go = (h) => page.evaluate((x) => { location.hash = x; }, h);
await go('#/figurinhas'); await page.waitForSelector('.fig-tabs', { timeout: 8000 });
check('abre o álbum', (await page.textContent('.fig-total')).includes('0/125'));
check('Geral tem 91 espaços numerados', (await page.locator('.fig-slot').count()) === 91);
await page.screenshot({ path: '/tmp/claude-0/fig-album.png' });
await page.getByRole('tab', { name: /pacotes/ }).click();
check('2 pacotes de presente (boas-vindas + do dia)', (await page.textContent('.fig-pack-card p')).startsWith('2 pacotes'));
await page.getByRole('button', { name: 'abrir pacote' }).click(); await sleep(500);
await page.screenshot({ path: '/tmp/claude-0/fig-pack.png' });
check('5 cartas no pacote', (await page.locator('.fig-flip').count()) === 5);
for (const b of await page.locator('.fig-flip').all()) await b.click();
await sleep(700); await page.screenshot({ path: '/tmp/claude-0/fig-pack2.png' });
await page.getByRole('button', { name: 'colar tudo no álbum' }).click(); await sleep(400);
const after = await page.textContent('.fig-total');
check('colou (pelo menos 1 de 125)', /^[1-5]\/125/.test(after.trim()), after);
await page.reload(); await page.waitForSelector('.fig-tabs'); await sleep(600);
const again = await page.textContent('.fig-total');
check('progresso persiste ao recarregar', /^[1-5]\/125/.test(again.trim()), again);
await page.getByRole('tab', { name: /pacotes/ }).click();
check('reabrir o app não devolve o pacote já aberto', (await page.textContent('.fig-pack-card p')).startsWith('1 pacote'));
await page.getByRole('tab', { name: /geral/ }).click(); await sleep(800);
await page.locator('.fig-slot.got').first().click(); await sleep(500);
check('detalhe abre', await page.locator('.fig-zoom > svg').count() === 1);
await page.screenshot({ path: '/tmp/claude-0/fig-detail.png' });
await page.keyboard.press('Escape'); await sleep(400);
await page.getByRole('tab', { name: /beatles/ }).click();
check('Beatles tem 22 espaços', (await page.locator('.fig-slot').count()) === 22);
check('sem erros de página', errs.length === 0, errs.join(' | '));
await browser.close(); srv.close(); done();
