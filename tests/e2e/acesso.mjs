// Área dos alunos: sem código só Jogos/Tocar/Ranking e cadeados; com código liberado abre tudo.
import { serve, launch, sleep, check, done } from './harness.mjs';
const { srv, url } = await serve();
const { browser, ctx } = await launch();
let liberado = false;
await ctx.route('**/rest/v1/rpc/**', async (route) => {
  const req = route.request(); const fn = req.url().split('/').pop();
  const ok = (j) => route.fulfill({ status: 200, contentType: 'application/json', headers: { 'access-control-allow-origin': '*' }, body: JSON.stringify(j) });
  if (req.method() === 'OPTIONS') return route.fulfill({ status: 204, headers: { 'access-control-allow-origin': '*', 'access-control-allow-headers': '*' } });
  if (fn === 'album_ler') return ok({ n: 'Teste', a: [], l: {}, r: [0, 0] });
  if (fn === 'acesso_ler') return ok(liberado);
  if (fn === 'dicas_ler') return ok(liberado ? [{ n: 1, texto: 'Estude devagar primeiro.' }, { n: 2, texto: 'Use o metrônomo.' }] : []);
  if (fn === 'album_guardar') return ok([{ code: 'BEA-0042', dados: {} }]);
  return ok(null);
});
const page = await ctx.newPage();
const errs = []; page.on('pageerror', (e) => errs.push(String(e)));
await page.addInitScript(() => { localStorage.setItem('beaterista-aluno-nome', 'Teste'); });
await page.goto(url + '/aluno.html#/jogos');
await page.waitForSelector('.jg-card'); await sleep(500);
const navs = () => page.$$eval('.bottom-nav a', (a) => a.map((x) => x.textContent.trim()));
const cards = () => page.$$eval('.jg-card', (a) => a.map((x) => ({ t: x.textContent.replace('🔒', '').trim(), lock: !!x.querySelector('.ac-lock') })));
check('abas: Jogos, Estudos, Tocar e Ranking', JSON.stringify(await navs()) === JSON.stringify(['Jogos', 'Estudos', 'Tocar', 'Ranking']), JSON.stringify(await navs()));
let c = await cards();
check('explorar a bateria saiu dos jogos', !c.some((x) => /explorar/i.test(x.t)));
check('Beat Hero com cadeado', c.find((x) => /beat hero/i.test(x.t))?.lock === true);
check('quiz e letras (3 em 1) com cadeado', c.find((x) => /quiz e letras/i.test(x.t))?.lock === true);
check('quiz/caça/cruzadinha não aparecem separados', !c.some((x) => /^(quiz|caça-palavras|cruzadinha)$/i.test(x.t)));
check('fases e estrelas saiu da lista dos alunos', !c.some((x) => /fases e estrelas/i.test(x.t)));
check('toque as figuras não aparece pros alunos', !c.some((x) => /toque as figuras/i.test(x.t)));
const ordem = c.map((x) => x.t.toLowerCase()).slice(0, 12);
check('ordem pedida pela Bea', JSON.stringify(ordem) === JSON.stringify(['beat hero', 'toca aqui', 'figuras rítmicas', 'memória musical', 'uno musical', 'jogo da velha', 'quebra cabeça', 'cara a cara', 'quiz e letras', 'onde mora na pauta?', 'bingo', 'stop']), JSON.stringify(ordem));
check('Toca Aqui livre', c.find((x) => /toca aqui/i.test(x.t))?.lock === false);
await page.evaluate(() => { location.hash = '#/estudos'; }); await sleep(600);
const est = await page.$$eval('#view a.card', (a) => a.map((x) => ({ t: x.textContent.replace('🔒', '').trim(), lock: x.classList.contains('locked') })));
check('Estudos sem código: aulinha, dicionário musical e dicas travados', ['Aulinha', 'Dicionário musical', '30 dicas'].every((n) => est.find((x) => x.t.includes(n))?.lock === true), JSON.stringify(est));
check('Estudos sem código: só "Jogos Ensinam" aberto', est.find((x) => /Jogos Ensinam/.test(x.t))?.lock === false);
await page.evaluate(() => { location.hash = '#/dicionario'; }); await sleep(600);
check('dicionário sem código volta pra Estudos', /#\/estudos/.test(await page.evaluate(() => location.hash)));
await page.keyboard.press('Escape'); await sleep(300);
await page.evaluate(() => { location.hash = '#/jogos/relatorio'; }); await sleep(600);
check('relatório abre pra todo mundo', /Jogos Ensinam/.test(await page.textContent('#view')));
await page.evaluate(() => { location.hash = '#/ranking'; }); await sleep(500);
check('Ranking leva ao álbum', await page.$('a[href="#/kids"]') !== null);
await page.evaluate(() => { location.hash = '#/kids/album'; }); await sleep(600);
check('álbum acende a aba Ranking', /Ranking/.test(await page.textContent('.bottom-nav a.on')));
await page.evaluate(() => { location.hash = '#/beatlab'; }); await sleep(500);
check('Beat Lab sem código volta pros jogos', /#\/jogos/.test(await page.evaluate(() => location.hash)));
await sleep(300); await page.keyboard.press('Escape'); await sleep(400);
await page.evaluate(() => { location.hash = '#/jogos/stop'; }); await sleep(500);
await page.click('#view button:text-is("JOGAR")'); await page.waitForSelector('.jg-seg'); check('STOP: modo sala de aula com cadeado', /🔒 sala de aula/.test(await page.textContent('#view')), (await page.textContent('.jg-seg')).slice(0, 80));
await page.evaluate(() => { location.hash = '#/jogos'; }); await sleep(500);
// libera: abre o cadeado, digita o código
liberado = true;
await page.click('.jg-card.locked'); await sleep(500);
await page.fill('.sheet input', '0042'); await page.click('.sheet button:text-is("liberar")'); await sleep(1200);
check('depois do código: 4 abas com Beat Lab', JSON.stringify(await navs()) === JSON.stringify(['Jogos', 'Estudos', 'Beat Lab', 'Tocar', 'Ranking']), JSON.stringify(await navs()));
c = await cards();
check('cadeados somem', !c.some((x) => x.lock));
await page.reload(); await page.waitForSelector('.jg-card'); await sleep(900);
await page.evaluate(() => { location.hash = '#/estudos/dicas'; }); await sleep(900);
check('30 dicas abrem com código liberado', /Estude devagar primeiro/.test(await page.textContent('#view')));
await page.evaluate(() => { location.hash = '#/dicionario'; }); await sleep(900);
check('dicionário abre com código liberado', /\/dicionario|Dicionário/.test(await page.textContent('#view')) && !/#\/estudos/.test(await page.evaluate(() => location.hash)));
check('continua liberado depois de recarregar', (await navs()).includes('Beat Lab'));
check('sem erros de JS', errs.length === 0, errs.join('|'));
await browser.close(); srv.close && srv.close(); done();
